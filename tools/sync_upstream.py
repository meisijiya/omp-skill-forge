def copy_file(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)


def refresh_pool(path, report, commit, version):
    picore, origin = resolve_picore(path)
    print(f"pi/core source: {origin}")

    mapping = {
        "skills": (os.path.join(picore, "skills"), os.path.join(POOL, "skills"), True),
        "commands": (os.path.join(picore, "commands"), os.path.join(POOL, "commands"), False),
        "agents": (os.path.join(path, "agents"), os.path.join(POOL, "agents"), False),
    }
    for kind, (src, dst, is_dir) in mapping.items():
        if not os.path.isdir(src):
            raise SystemExit(f"upstream {kind} source missing: {src}")
        changed = 0
        added = 0
        removed = 0
        if os.path.isdir(dst):
            for name in sorted(os.listdir(dst)):
                s = os.path.join(src, name)
                d = os.path.join(dst, name)
                if not os.path.exists(s):
                    removed += 1
                    if os.path.isdir(d) and not os.path.islink(d):
                        shutil.rmtree(d)
                    else:
                        os.remove(d)
                    continue
                if is_dir:
                    if not dirs_equal(s, d):
                        changed += 1
                        shutil.rmtree(d)
                        shutil.copytree(s, d)
                else:
                    if not files_equal(s, d):
                        changed += 1
                        copy_file(s, d)
            for name in sorted(os.listdir(src)):
                s = os.path.join(src, name)
                d = os.path.join(dst, name)
                if os.path.exists(d):
                    continue
                added += 1
                if is_dir:
                    shutil.copytree(s, d)
                else:
                    copy_file(s, d)
        else:
            # Target does not exist yet: copy the whole tree in one go.
            # Do NOT pre-create the destination (copytree would then fail with
            # FileExistsError).
            if is_dir:
                shutil.copytree(src, dst, dirs_exist_ok=True)
            else:
                os.makedirs(dst, exist_ok=True)
                for name in sorted(os.listdir(src)):
                    s = os.path.join(src, name)
                    if not os.path.isfile(s):
                        # Skip sub-directories: copy2() on a directory raises
                        # IsADirectoryError.
                        continue
                    copy_file(s, os.path.join(dst, name))
        report.append(f"{kind}: +{added} ~{changed} -{removed}")

    digest = compute_pool_digest(POOL)
    recorded = read_recorded_manifest()
    recorded_digest = recorded.get("pool_digest")
    recorded_commit = recorded.get("commit")

    # The pin describes the vendored content, not the upstream commit count:
    # it only moves when the pool content actually changed (ADR-0017).
    if recorded_digest is not None and recorded_digest == digest:
        pin_commit = recorded_commit or commit
        pin_version = recorded.get("version") or version or "unknown"
        print("pool content unchanged: the recorded pin stays where it is")
    else:
        pin_commit = commit
        # 上游该 commit 没有 VERSION 文件时沿用已记录的版本号：三处镜像要么
        # 写同一个版本，要么都不写，不能一处写 unknown 而另两处留着旧值。
        pin_version = version if version is not None else (recorded.get("version") or "unknown")
        if recorded_digest is not None:
            print("pool content changed: the pin advances to the synced commit")

    meta = {
        "repo": REPO_URL,
        "commit": pin_commit,
        "version": pin_version,
        "pool_digest": digest,
    }
    write_upstream_manifest(meta)
    # The hand written copies of the pin may not drift away from it.
    update_groups_upstream(pin_commit, pin_version if pin_version != "unknown" else None)
    update_notice(pin_commit, pin_version, pool_counts())
    print("upstream:", meta)

    if recorded_commit is not None and pin_commit != recorded_commit:
        print("pin advanced: re-record the asset ledger with")
        print("  python tools/upstream_versions.py record --source ecc")
    return pin_commit, digest


def main():
    ap = argparse.ArgumentParser(
        description="Fetch upstream ECC, refresh pool/, and replay the local selection.",
    )
    ap.add_argument("--pool-only", action="store_true",
                    help="only refresh pool/ and the pin files; do not replay the selection")
    ap.add_argument("--no-fetch", action="store_true",
                    help="do not contact the network; work with the existing clone")
    ap.add_argument("--checkout", metavar="SHA", default=None,
                    help="pin the upstream to this commit (40 hex chars): fetch it and "
                         "check it out detached; with --no-fetch use the commit that is "
                         "already in the local clone")
    args = ap.parse_args()

    sha = normalize_sha(args.checkout) if args.checkout is not None else None

    if sha is None:
        source, ours = resolve_source()
        if not args.no_fetch:
            fetch(source, ours)
        else:
            print("fetch skipped (--no-fetch)")
            if not ours:
                print(f"using omp marketplace cache clone (read-only): {source}")
                check_clean_cache(source)
    elif args.no_fetch:
        source, ours = resolve_offline_source(sha)
        print("fetch skipped (--no-fetch)")
    else:
        # A specific commit has to be checked out inside a clone this repo
        # owns, so the read-only marketplace cache is not a candidate here.
        source, ours = resolve_source(need_writable=True)

    if sha is not None:
        if not args.no_fetch:
            if not fetch_commit(source, sha):
                raise SystemExit(
                    f"cannot fetch commit {sha} from {REPO_URL}: the commit does not "
                    f"exist upstream, or the remote refuses to serve it by id"
                )
        checkout_commit(source, sha, ours)

    commit, version = report_source(source, ours)
    if sha is not None and commit != sha:
        raise SystemExit(
            f"checked out {sha} but the source reports {commit}; refusing to pin a "
            f"commit the pool was not taken from"
        )

    report = []
    refresh_pool(source, report, commit, version)
    for line in report:
        print(line)

    if not args.pool_only:
        print("\nreplaying selection...")
        subprocess.run(
            [sys.executable, os.path.join(ROOT, "tools", "apply_selection.py")], check=True
        )


if __name__ == "__main__":
    main()
